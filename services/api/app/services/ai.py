"""Optional AI helpers (docs/product/ai-usage.md). Never part of a credit decision.

Default: deterministic templates. With OLLAMA_URL set, a local open-weight model rewrites wording
within a timeout; numbers are never generated by the model (placeholders are substituted after
generation) and any failure or invalid output falls back to the template.
"""

from __future__ import annotations

import json
import logging
import re
import time
from decimal import Decimal
from typing import Any

import httpx

from ..config import get_settings
from ..domain.dictionaries import fmt_dt, fmt_money

log = logging.getLogger("app.ai")
LABEL = "Сформировано автоматически, проверьте по данным карточки"


def _ollama(prompt: str, *, json_mode: bool) -> str | None:
    s = get_settings()
    if not s.ollama_url:
        return None
    try:
        with httpx.Client(timeout=s.ai_timeout_seconds) as http:
            resp = http.post(
                s.ollama_url.rstrip("/") + "/api/generate",
                json={"model": s.ollama_model, "prompt": prompt, "stream": False, "format": "json" if json_mode else None, "options": {"temperature": 0.2, "num_predict": 400}},
            )
        resp.raise_for_status()
        return resp.json().get("response")
    except (httpx.HTTPError, ValueError) as exc:
        log.warning("ollama unavailable, template used", extra={"fields": {"error": type(exc).__name__}})
        return None


def summary_input(card: dict[str, Any]) -> dict[str, Any]:
    """Structured fields only: no names, INN, document numbers or client free text."""
    scoring = card.get("scoring") or {}
    contributions = sorted(scoring.get("factor_contributions") or [], key=lambda f: f["points"])
    policy_decisions = [d for d in card.get("decisions", []) if d["mode"] == "AUTO"]
    last = policy_decisions[-1] if policy_decisions else None
    company = card.get("company") or {}
    open_items = [i for ir in card.get("info_requests", []) if ir and ir["status"] == "OPEN" for i in ir["items"]]
    return {
        "product": card["product_name"],
        "amount": card["form"].get("amount"),
        "term_months": card["form"].get("term_months"),
        "purpose": card["purpose_title"],
        "industry": company.get("okved_main_name"),
        "registration_date": company.get("registration_date"),
        "grade": scoring.get("grade"),
        "score": scoring.get("score"),
        "weakest_factors": [{"factor": f["factor_name"], "value": f["value"], "points": f["points"]} for f in contributions[:3] if f["points"] < 0],
        "strongest_factors": [{"factor": f["factor_name"], "value": f["value"], "points": f["points"]} for f in contributions[-3:] if f["points"] > 0],
        "rules": last["rules_path"] if last else [],
        "manual_review_reasons": [r["employee_text"] for r in card.get("manual_review_reasons", [])],
        "discrepancies": [d["text"] for d in card.get("discrepancies", [])],
        "recommendation": (last or {}).get("recommendation"),
        "open_info_items": len(open_items),
    }


def template_summary(data: dict[str, Any]) -> dict[str, list[str]]:
    risks = [f"{f['factor']}: {f['value']} ({f['points']} баллов)" for f in data["weakest_factors"]]
    risks += data["discrepancies"]
    checks = list(data["manual_review_reasons"])
    if data["open_info_items"]:
        checks.append(f"Открытых пунктов дозапроса: {data['open_info_items']}")
    rec = data.get("recommendation") or {}
    if rec:
        checks.append(f"Рекомендация политики: {rec.get('outcome')}, максимум на запрошенный срок {fmt_money(rec.get('max_amount_requested_term'))}")
    positives = [f"{f['factor']}: {f['value']} (+{f['points']} баллов)" for f in data["strongest_factors"]]
    if data.get("grade"):
        positives.insert(0, f"Грейд {data['grade']}, балл {data['score']}")
    return {"risks": risks[:3] or ["Существенных отрицательных факторов не найдено"], "checks": checks[:3] or ["Дополнительных проверок не требуется"], "positives": positives[:3] or ["Нет выраженных положительных факторов"]}


def underwriter_summary(card: dict[str, Any]) -> dict[str, Any]:
    data = summary_input(card)
    started = time.perf_counter()
    blocks = template_summary(data)
    fallback = True
    s = get_settings()
    raw = _ollama(
        "Ты помогаешь кредитному аналитику банка. По структурированным данным заявки (JSON ниже) составь краткое резюме на русском языке "
        "в виде JSON с ключами risks, checks, positives: в каждом от 1 до 3 коротких пунктов. Не придумывай чисел, которых нет в данных. "
        "Не давай итогового решения по кредиту.\nДанные: " + json.dumps(data, ensure_ascii=False, default=str),
        json_mode=True,
    )
    if raw:
        try:
            parsed = json.loads(raw)
            candidate = {k: [str(x)[:300] for x in parsed.get(k, [])][:3] for k in ("risks", "checks", "positives")}
            if all(candidate.values()):
                blocks, fallback = candidate, False
        except (ValueError, AttributeError):
            pass
    return {
        "blocks": blocks,
        "label": LABEL,
        "model_name": None if fallback else s.ollama_model,
        "fallback_used": fallback,
        "latency_ms": int((time.perf_counter() - started) * 1000),
    }


_NUMBER = re.compile(r"\d")


def plain_explanation(view: dict[str, Any]) -> dict[str, Any]:
    """'Explain simpler' for the offer or the decline: template text, optionally reworded by the model with placeholders."""
    offer = view.get("offer")
    placeholders: dict[str, str] = {}
    if offer and offer.get("options"):
        o = next((x for x in offer["options"] if x["recommended"]), offer["options"][0])
        placeholders = {
            "[СУММА]": rub(o["amount"]), "[СРОК]": months(o["term_months"]), "[ПЛАТЕЖ]": rub(o["monthly_payment"]),
            "[ПЕРЕПЛАТА]": rub(o["overpayment"]), "[СТАВКА]": f"{Decimal(o['rate_percent']).normalize()}%", "[ДО]": fmt_dt_iso(offer["expires_at"]),
        }
        template = (
            "Банк готов дать [СУММА] на [СРОК]. Каждый месяц нужно платить [ПЛАТЕЖ]. За весь срок вы заплатите банку сверху [ПЕРЕПЛАТА], "
            "это и есть стоимость кредита при ставке [СТАВКА] в год. Решить, подходит ли предложение, нужно до [ДО]."
        )
        if offer["outcome"] == "COUNTER_OFFER":
            template = "Банк не может дать ровно то, что вы просили, потому что платеж был бы слишком большим для выручки бизнеса. " + template
    elif view.get("decision"):
        reasons = view["decision"]["reasons"]
        template = " ".join(f"{r['text']} {r['next_step'] or ''}".strip() for r in reasons)
    else:
        template = view["client_status_text"]["what_is_happening"] + " " + view["client_status_text"]["what_next"]
    text, fallback = template, True
    raw = _ollama(
        "Перепиши текст для предпринимателя без банковского опыта простыми словами, 2-3 предложения, на русском. "
        "Сохрани все метки в квадратных скобках без изменений, не добавляй чисел.\nТекст: " + template,
        json_mode=False,
    )
    if raw and all(p in raw for p in placeholders) and not _NUMBER.search(raw) and len(raw) < 1200:
        text, fallback = raw.strip(), False
    for key, value in placeholders.items():
        text = text.replace(key, value)
    return {"text": text, "label": "Пояснение сформировано автоматически" if not fallback else None, "fallback_used": fallback}


def rub(value) -> str:
    return fmt_money(value).replace(" руб.", " ₽")


def months(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return f"{n} месяц"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return f"{n} месяца"
    return f"{n} месяцев"


def fmt_dt_iso(value: str | None) -> str:
    from datetime import datetime

    return fmt_dt(datetime.fromisoformat(value.replace("Z", "+00:00"))) if value else ""
